"""Small structural interfaces; application services do not import bpy."""
from typing import Any, ContextManager, Protocol


class MeshRepositoryPort(Protocol):
    def editable_object(self, context: Any) -> Any: ...
    def validate_attributes(self, mesh: Any) -> None: ...
    def open_mesh(self, obj: Any, write: bool = False) -> ContextManager[Any]: ...
    def selected_faces(self, bm: Any) -> list[Any]: ...
    def masks_of(self, bm: Any) -> dict[int, int]: ...
    def plan_auto(self, bm: Any, masks: dict[int, int], angle: float) -> Any: ...
    def derive(self, bm: Any, masks: dict[int, int]) -> Any: ...
    def commit(self, bm: Any, masks: dict[int, int], derived: Any) -> None: ...


class NormalBackendPort(Protocol):
    def validate_stack(self, obj: Any) -> None: ...
    def ensure_normals(self, obj: Any) -> Any: ...
    def move_to(self, obj: Any, modifier: Any, index: int) -> None: ...
    def sync_visibility(self, obj: Any) -> None: ...


class SubdivisionBackendPort(Protocol):
    def subdivision(self, obj: Any) -> Any: ...
    def validate_subdivision_support(self) -> None: ...
    def add_subdivision(self, obj: Any) -> Any: ...
